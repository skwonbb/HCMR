import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
N = Path(__file__).resolve().parent.parent / "results" / "noise"
D = N / "infer"
PREP = json.loads((D / "state_prep_2q_gates.json").read_text())
SETS = [("amplitude", 4), ("amplitude", 8), ("angle", 4), ("angle", 8)]
ENC_KO = {"amplitude": "amplitude", "angle": "angle"}
VARS = [("base", "reference (L = 4)"), ("L8", "L = 8"), ("L16", "L = 16"), ("zz", "Z + ZZ"), ("hcmr", "HCMR (linear)"),
        ("hcmr_cnn", "HCMR (CNN)")]
BACK = [("fez", "FakeFez"), ("nighthawk", "FakeNighthawk")]
COND = ["ideal", "shots_only", "noise_only", "both"]
out, js = ["# Section 5.4 paper tables (generated by analysis/noise_tables.py)", ""], {"exp2": {}, "exp1": {}}


DSS = ("mnist", "fmnist")
DS_KO = {"mnist": "MNIST", "fmnist": "FMNIST"}
SCOPES = [(None, DSS), ("mnist", ("mnist",)), ("fmnist", ("fmnist",))]


def per_seed(fn, dss=DSS):
    v = [np.mean([fn(ds, s) for ds in dss]) for s in range(5)]
    return float(np.mean(v)), float(np.std(v))


def key(scope, rest):
    return rest if scope is None else f"{scope}/{rest}"


for be, bname in BACK:
    for enc, nq in SETS:
        for v, _ in VARS:
            p = D / be / f"{enc}_{{}}_{nq}q4c" / v
            J = {(ds, s): json.loads((Path(str(p).format(ds)) / f"seed_{s}.json").read_text())
                 for ds in ("mnist", "fmnist") for s in range(5)}
            Z = {(ds, s): np.load(Path(str(p).format(ds)) / f"seed_{s}.npz") for ds in ("mnist", "fmnist") for s in range(5)}

            def tv(ds, s, norm):
                z = Z[(ds, s)]; pi = z["prob_ideal"].astype(float)
                t = 0.5 * np.abs(pi - z["prob_noise"].astype(float)).sum(1)
                return (t / (0.5 * np.abs(pi - 1 / pi.shape[1]).sum(1))).mean() if norm else t.mean()
            for scope, dss in SCOPES:
                e = {f"acc_{c}": per_seed(lambda ds, s, c=c: 100 * J[(ds, s)][c]["acc"], dss) for c in COND}
                for reg in ("acc_ce", "acc_pe"):
                    for c in ("ideal", "both"):
                        e[f"{reg}_{c}"] = per_seed(lambda ds, s, c=c, reg=reg: 100 * J[(ds, s)][c][reg], dss)
                e["tvd_noise"] = per_seed(lambda ds, s: tv(ds, s, False), dss)
                e["tvd_noise_norm"] = per_seed(lambda ds, s: tv(ds, s, True), dss)
                tot = float(np.mean([r["two_qubit_gates_mean"] for (ds, _), r in J.items() if ds in dss]))
                prep = PREP[f"{be}/{enc}_{nq}q/{v}"]
                e["gates_prep"], e["gates_pqc"], e["gates_total"] = prep, tot - prep, tot
                js["exp2"][key(scope, f"{be}/{enc}_{nq}q/{v}")] = e

f1 = lambda m: f"{m[0]:.1f}"
pm = lambda m: f"{m[0]:.1f} ± {m[1]:.1f}"

out += ["## 2-qubit gates (cz) on FakeFez (state preparation / PQC; the PQC includes routing SWAPs)", "",
        "| embedding | qubits | L = 4 (reference, Z + ZZ) | L = 8 | L = 16 | HCMR (L = 4) |", "|---|---|---|---|---|---|"]
for enc, nq in SETS:
    c = [js["exp2"][f"fez/{enc}_{nq}q/{v}"] for v in ("base", "L8", "L16", "hcmr")]
    out.append(f"| {ENC_KO[enc]} | {nq} | " + " | ".join(f"{x['gates_prep']:.0f} / {x['gates_pqc']:.0f}" for x in c) + " |")
out.append("")

for be, bname in BACK:
    out += [f"## Inference noise, all settings, {bname}", "",
            "| dataset | embedding | qubits | variant | ideal | shots only | device noise only | both | CE ideal | CE both | PE ideal | PE both "
            "| TVD | normalized TVD | cz state preparation | cz PQC |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for ds in DSS:
      for enc, nq in SETS:
        for v, vn in VARS:
            e = js["exp2"][key(ds, f"{be}/{enc}_{nq}q/{v}")]
            out.append(f"| {DS_KO[ds]} | {ENC_KO[enc]} | {nq} | {vn} | " + " | ".join(pm(e[f"acc_{c}"]) for c in COND)
                       + f" | {f1(e['acc_ce_ideal'])} | {f1(e['acc_ce_both'])} | {f1(e['acc_pe_ideal'])} | {f1(e['acc_pe_both'])}"
                       + f" | {e['tvd_noise'][0]:.3f} | {e['tvd_noise_norm'][0]:.3f} | {e['gates_prep']:.0f} | {e['gates_pqc']:.0f} |")
    out.append("")

T = N / "train"
for enc, nq in SETS:
    for m in ("hcmr", "hcmr_cnn"):
        for c in ("none", "shots", "device", "both"):
            R = {(ds, s): json.loads((T / c / f"{enc}_{ds}_{nq}q4c" / m / f"seed_{s}.json").read_text())
                 for ds in ("mnist", "fmnist") for s in range(5)}
            for scope, dss in SCOPES:
                e = {}
                for j in ("0", "10", "60"):
                    e[f"acc_J{j}"] = per_seed(lambda ds, s, j=j: 100 * R[(ds, s)]["J"][j]["ideal"]["acc"], dss)
                    for reg in ("acc_ce", "acc_pe"):
                        e[f"{reg}_J{j}"] = per_seed(lambda ds, s, j=j, reg=reg: 100 * R[(ds, s)]["J"][j]["ideal"][reg], dss)
                    e[f"ce_size_J{j}"] = per_seed(lambda ds, s, j=j: 100 * R[(ds, s)]["J"][j]["ce_size_test"], dss)
                    if j != "0":
                        e[f"drift_J{j}"] = per_seed(lambda ds, s, j=j: R[(ds, s)]["J"][j]["encoder_drift"], dss)
                js["exp1"][key(scope, f"{enc}_{nq}q/{m}/{c}")] = e

CK = {"none": "none", "shots": "shots only", "device": "device noise only", "both": "both"}
MK = {"hcmr": "linear", "hcmr_cnn": "CNN"}
out += ["## Training noise (accuracy % with noiseless inference, mean of the linear and CNN encoders)", "",
        "| embedding | qubits | J | none | shots only | device noise only | both |", "|---|---|---|---|---|---|---|"]
for enc, nq in SETS:
    for j in ("10", "60"):
        out.append(f"| {ENC_KO[enc]} | {nq} | {j} | " + " | ".join(
            f"{np.mean([js['exp1'][f'{enc}_{nq}q/{m}/{c}'][f'acc_J{j}'][0] for m in ('hcmr', 'hcmr_cnn')]):.1f}" for c in CK) + " |")
out += ["", "## Training noise, all settings (accuracy % with noiseless inference)", "",
        "| dataset | embedding | qubits | encoder | J | none | shots only | device noise only | both |",
        "|---|---|---|---|---|---|---|---|---|"]
for ds in DSS:
    for enc, nq in SETS:
        for m in ("hcmr", "hcmr_cnn"):
            for j in ("10", "60"):
                out.append(f"| {DS_KO[ds]} | {ENC_KO[enc]} | {nq} | {MK[m]} | {j} | "
                           + " | ".join(pm(js["exp1"][key(ds, f"{enc}_{nq}q/{m}/{c}")][f"acc_J{j}"]) for c in CK) + " |")
out += ["", "## Training noise, amplitude 8 qubits (CE / PE accuracy %, CE size %, encoder drift)", "",
        "| dataset | encoder | training noise | J | CE accuracy | PE accuracy | CE size | encoder drift |",
        "|---|---|---|---|---|---|---|---|"]
for ds in DSS:
    for m in ("hcmr", "hcmr_cnn"):
        for c in CK:
            e = js["exp1"][key(ds, f"amplitude_8q/{m}/{c}")]
            for j in ("10", "60"):
                out.append(f"| {DS_KO[ds]} | {MK[m]} | {CK[c]} | {j} | {pm(e[f'acc_ce_J{j}'])} | {pm(e[f'acc_pe_J{j}'])} "
                           f"| {pm(e[f'ce_size_J{j}'])} | {e[f'drift_J{j}'][0]:.2f} ± {e[f'drift_J{j}'][1]:.2f} |")
(N / "paper_tables.md").write_text("\n".join(out) + "\n", encoding="utf-8")
(N / "paper_tables.json").write_text(json.dumps(js, indent=1), encoding="utf-8")
print("saved", N / "paper_tables.md")
